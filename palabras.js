// Nombre del archivo de audio: sin tildes, ñ -> ny, en minúsculas
self.clipNorm = function (s) {
  return s.toLowerCase().replace(/ñ/g, 'ny').normalize('NFD').replace(/[\u0300-\u036f]/g, '');
};
// Una R entre vocales suena suave (PE-RA, LO-RO); al principio, fuerte (RA-NA)
self.silabaClip = function (sils, i) {
  var s = sils[i];
  var soft = i > 0 && /^r[aeiouáéíóú]/i.test(s) && /[aeiouáéíóú]$/i.test(sils[i - 1]);
  return 's-' + self.clipNorm(s) + (soft ? '-suave' : '');
};
self.palabraClip = function (w) { return 'w-' + self.clipNorm(w.replace(/-/g, '')); };
// Nombre de una letra suelta ("la eme"): l-m.mp3
self.letraClip = function (l) { return 'l-' + self.clipNorm(l); };
// Letras de una sílaba; LL y CH cuentan como una sola letra: 'LLA' -> ['LL', 'A']
self.letrasDe = function (syl) { return syl.match(/LL|CH|RR|./gi) || []; };
